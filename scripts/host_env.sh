# Настройки скриптов хоста — бэкапа, внешней копии, алертов: из окружения,
# иначе из .env рядом с компоузом, где их же читают контейнеры.
#
# Подключается через `.` и сам ничего не делает. `.env` не исполняется
# (`source .env`): файл пишется для компоуза, а не для bash, и значение с `$`,
# пробелом или скобкой сработало бы как команда. Берётся строка `ИМЯ=значение`,
# последняя — как у компоуза; кавычки вокруг значения снимаются.
#
# ENV_FILE — другой файл (по умолчанию .env в корне репозитория, $ROOT).

host_env() {
  local name="$1" file="${ENV_FILE:-$ROOT/.env}" value=""
  if [ -n "${!name:-}" ]; then
    printf '%s' "${!name}"
    return 0
  fi
  [ -r "$file" ] || return 0
  value="$(sed -n "s/^${name}=//p" "$file" | tail -n 1)"
  value="${value%$'\r'}"
  case "$value" in
    \"*\" | \'*\') value="${value:1:${#value}-2}" ;;
  esac
  printf '%s' "$value"
}
