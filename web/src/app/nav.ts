/**
 * Разделы сервиса и права, которые они требуют.
 *
 * Одно место, где решается «кому что видно». Разъехавшись по компонентам, это
 * правило перестанет совпадать с серверным — и человек увидит кнопку, ведущую
 * к `403`, то есть интерфейс, который врёт.
 *
 * Скрытая кнопка при этом **не защита**: проверки на роутерах стоят и остаются.
 */

export interface NavSection {
  path: string;
  label: string;
  /** Право, без которого раздел не показывается. `null` — виден всем вошедшим. */
  right: string | null;
}

export const NAV_SECTIONS: readonly NavSection[] = [
  // «Прогоны» первыми: с них начинается работа, и порядок меню — это порядок
  // сценария, а не алфавит.
  //
  // Раздел один, хотя прежде их было два — «Загрузка» и «Прогоны». Разделение
  // заставляло начинать работу в одном месте и смотреть результат в другом:
  // «Загрузка» кончалась кнопкой «Запустить прогон», а что из этого вышло,
  // показывал соседний раздел, и он же отсылал обратно текстом. Объединено по
  // решению владельца 15.09.2026.
  //
  // Право `run`, а не `read`: раздел не только показывает журнал, но и
  // принимает список и запускает прогон. Тому, у кого есть только `read`,
  // видеть кнопку, ведущую к `403`, незачем.
  { path: '/runs', label: 'Прогоны', right: 'run' },
  { path: '/projects', label: 'Проекты', right: 'read' },
  { path: '/cases', label: 'Кейсы', right: 'read' },
  { path: '/usage', label: 'Расход units', right: 'read' },
  // `edit_thresholds`, хотя предпросмотр в API открыт праву `read`: таблица
  // доступа ТЗ говорит про раздел «Пороги» — «Пользователь: нет», и расширять
  // её решает заказчик, а не мы. Открытый предпросмотр остаётся: он доступен
  // по API тому, кто спросит, и им пользуется тот, кто утверждает пороги.
  { path: '/thresholds', label: 'Пороги', right: 'edit_thresholds' },
  { path: '/users', label: 'Пользователи', right: 'manage_users' },
];

export function visibleSections(rights: readonly string[]): NavSection[] {
  return NAV_SECTIONS.filter((section) => section.right === null || rights.includes(section.right));
}
