/**
 * Почему собранный файл больше не про этот проект — словами.
 *
 * Одна формулировка на два экрана: карточка проекта и библиотека кейсов
 * показывают одно и то же состояние, и две редакции текста разошлись бы при
 * первой же правке (дубль ловится гейтом копипаста).
 *
 * Состояние заводится сервером (`cases/freshness.py`) и означает буквально:
 * числа в файле уже не те, что на экране. Замер 16.09.2026 — 51 проект из 62
 * с файлами от прежней группы.
 */
import type { CaseRow } from '../../api/types';
import { groupWord } from '../groups';

export interface StaleWords {
  /** Для тесной ячейки таблицы. */
  short: string;
  /** Для карточки, где есть место объяснить и назвать следующий шаг. */
  full: string;
}

export function staleWords(row: CaseRow): StaleWords {
  const was = row.case_group ? groupWord(row.case_group) : '—';
  const now = row.current_group ? groupWord(row.current_group) : '—';
  const rebuild = 'Пересоберите на экране «Кейсы».';
  switch (row.outdated) {
    case 'group':
      return {
        short: `собран для группы «${was}», сейчас «${now}» — пересоберите`,
        full: `Файл собран, когда проект был в группе «${was}», а сейчас он «${now}» — кейс этой группе не положен. ${rebuild}`,
      };
    case 'numbers':
      return {
        short: 'числа пересчитаны — пересоберите',
        full: `Файл собран по другим числам: вердикт с тех пор пересчитали. ${rebuild}`,
      };
    case 'verdict':
      return {
        short: 'собран другим расчётом — пересоберите',
        full: `Файл собран другим расчётом, а не действующим. ${rebuild}`,
      };
    default:
      return {
        short: 'вердикта больше нет — пересчитайте и пересоберите',
        full: 'У проекта нет действующего вердикта, а файл остался от прежнего. Пересчитайте и пересоберите.',
      };
  }
}
