/**
 * Предупреждение: числа вердикта и кривые — из разных данных.
 *
 * Таблица А → Б приходит из записанного вердикта, кривые — из рядов
 * запрошенного источника. Когда это не одни и те же данные, экран обязан
 * сказать об этом раньше, чем человек начнёт сверять числа глазами: кейс по
 * такому вердикту не собирается вовсе (Z10).
 *
 * Само расхождение находит сервер — правило одно на лист PDF и на карточку.
 * Здесь только показ и следующий шаг, который у всех трёх случаев один.
 */
import { Alert, Text } from '@mantine/core';

export function SourceMismatch({ reason }: { reason: string | null }) {
  if (!reason) {
    return null;
  }
  return (
    <Alert color="red" variant="light" title="Числа и кривые — из разных данных">
      <Text size="sm">
        {reason}. Кейс по такому вердикту не собирается. Запустите классификацию — она бесплатна и
        считает по уже собранным данным.
      </Text>
    </Alert>
  );
}
