/**
 * Группа проекта словом и цветом.
 *
 * Групп **четыре, а не три**: «данных не хватает» — своя, не «плохой». Разница
 * не в оттенке, а в действии человека: у «плохого» результат есть и он слабый
 * (кейса не будет), у «нет данных» работа не закончена (докупить историю и
 * пересчитать). Слить их на экране значит потерять различие ровно там, где его
 * читают.
 *
 * Отсутствие группы — тоже ответ: проект собран, но действующей версией порогов
 * ещё не классифицирован. Пустая ячейка на этом месте читалась бы как ошибка
 * загрузки.
 */
import { Badge, Text } from '@mantine/core';

import { groupInk } from '../../theme';
import { groupWord } from '../groups';

export function GroupBadge({ group }: { group: string | null }) {
  if (!group) {
    return (
      <Text size="sm" c="dimmed">
        не классифицирован
      </Text>
    );
  }
  return (
    <Badge
      variant="light"
      // Цвет берётся из общего словаря: та же метрика и та же группа окрашены
      // одинаково в бейдже, на плитке и на кривой.
      style={{ color: groupInk[group as keyof typeof groupInk] ?? 'inherit' }}
      data-group={group}
    >
      {groupWord(group)}
    </Badge>
  );
}
