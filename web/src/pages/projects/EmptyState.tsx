/**
 * Пусто — но по разным причинам, и это разные тексты.
 *
 * «Ничего не нашлось» при пустой базе отправило бы человека снимать фильтры,
 * которых он не ставил; «загрузите список» при активном фильтре — искать
 * загрузку, которая уже была.
 */
import { Alert, Text } from '@mantine/core';

export function EmptyState({ filtered }: { filtered: boolean }) {
  return (
    <Alert color="yellow" variant="light">
      <Text size="sm">
        {filtered
          ? 'Под фильтры ничего не подошло. Снимите фильтр или измените поиск.'
          : 'Проектов пока нет. Загрузите список на экране «Загрузка».'}
      </Text>
    </Alert>
  );
}
