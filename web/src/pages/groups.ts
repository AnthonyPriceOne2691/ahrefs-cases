/**
 * Как называются группы. Одно место на весь интерфейс.
 *
 * Групп **четыре, а не три**: «данных не хватает» — своя, не «плохой». Разница
 * не в оттенке, а в действии человека: у «плохого» результат есть и он слабый,
 * у «нет данных» работа не закончена (докупить историю и пересчитать).
 *
 * Словарь вынесен из бейджа проекта, когда прогон живого экрана показал в
 * предпросмотре порогов «good → poor» посреди русского экрана: одно и то же
 * название, живущее в двух местах, расходится молча.
 */
export const GROUP_LABELS: Record<string, string> = {
  good: 'хороший',
  medium: 'средний',
  poor: 'плохой',
  insufficient_data: 'данных не хватает',
};

/** Незнакомое значение показываем как есть: выдумывать ему слово опаснее, чем
 *  показать сырое — по нему хотя бы понятно, что сервис знает больше экрана. */
export function groupWord(group: string): string {
  return GROUP_LABELS[group] ?? group;
}
