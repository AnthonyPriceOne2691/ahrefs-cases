"""Коды отказа при приёме списка. Строка не проходит — прогон продолжается.

Требование ТЗ прямое: битая строка не останавливает загрузку остальных. Значит
отказ обязан быть **данными** (код + поле + строка источника), а не исключением:
исключение прерывает разбор, а его текст невозможно показать на экране Ф6 иначе
как строкой лога.

Коды — часть контракта с фронтом: экран группирует отказы по `reason`, поэтому
новый код добавляется здесь, а не собирается из f-строк по месту.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class RejectReason(StrEnum):
    """Почему строка не стала проектом."""

    EMPTY_DOMAIN = "empty_domain"
    INVALID_DOMAIN = "invalid_domain"
    IP_ADDRESS = "ip_address"
    """IP вместо домена: Ahrefs считает по хосту, и такой «проект» не соберётся."""

    EMPTY_SOURCE = "empty_source"
    """Источник прочитан, но в нём нет ни одной колонки: пустой файл, не тот лист,
    выгрузка без заголовка. Один отказ на файл, а не десять «нет колонки»."""

    MISSING_FIELD = "missing_field"
    MISSING_COLUMN = "missing_column"
    """Нет самой колонки — брак не строки, а файла: отчёт скажет это один раз."""

    BAD_DATE = "bad_date"
    PERIOD_ORDER = "period_order"
    BAD_GEO = "bad_geo"
    BAD_ENUM = "bad_enum"
    BAD_NUMBER = "bad_number"
    BAD_FLAG = "bad_flag"
    DUPLICATE_IN_SOURCE = "duplicate_in_source"
    """Домен встречается в файле дважды. Побеждает последняя строка, но обе
    попадают в отчёт: тихое схлопывание скрыло бы ошибку в самом списке."""


@dataclass(frozen=True, slots=True)
class Rejection:
    """Отказ по конкретной строке источника.

    `row_no` — номер строки **в источнике**, включая заголовок, а не индекс в
    массиве: человек будет искать её глазами в Excel, и off-by-one здесь стоит
    ему минуты на каждой строке.
    """

    row_no: int
    field: str
    reason: RejectReason
    detail: str = ""


@dataclass(frozen=True, slots=True)
class Notice:
    """Поле, которое не разобрали, — **строка при этом принята**.

    Свой тип, а не флаг внутри `Rejection`, потому что последствие другое, а
    последствие — это всё, что отличает эти две новости. С флагом каждый
    читатель отчёта обязан о нём помнить; забывший посчитает замечания
    отклонёнными строками, и число «отклонено строк» начнёт врать.

    Замечание законно там, где поле **разрешено не знать** и оно не участвует
    в расчётах. Сегодня такое поле одно — `work_volume`: ТЗ описывает его
    нестрого («объём работ, например число построенных ссылок»), модель
    разрешает ему быть пустым, а кейс без него просто скрывает блок «что
    сделали». Ронять из-за подписи «214 ссылок» проект, у которого домен, даты
    и гео в порядке, значит терять кейс из-за формы записи в одной ячейке.

    Обратное так же важно: у домена, дат, гео и флага публикации замечаний не
    бывает. Без первых двух проект не собирается вовсе, а гео и флаг — защиты
    (стоп-лист стран и право называть клиента), и смягчить их значит снять их.
    """

    row_no: int
    field: str
    reason: RejectReason
    detail: str = ""
