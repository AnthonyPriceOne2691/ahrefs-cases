"""Схемы ответов API. Ровно то, что нужно экрану, и ничего сверх.

Модели домена наружу не отдаются: у `Project` есть клиент и ответственный, у
`Verdict` — внутренний `ruleset_id`, и решать, что из этого видно снаружи,
должен один явный слой, а не сериализатор по умолчанию.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Literal

from pydantic import BaseModel, Field

MAX_PAGE = 100
"""Потолок выдачи. Не вкус: карточка тянет ряды по месяцам, и «отдать всё»
перестаёт работать незаметно ровно тогда, когда данных станет много."""


class ProjectRow(BaseModel):
    """Строка таблицы проектов: то, по чему сортируют и фильтруют."""

    id: int
    domain: str
    niche: str
    geo: str
    service_type: str
    period_start: date
    period_end: date
    publishable: bool
    status: str
    group: str | None = None
    """`None` — проект не классифицирован действующей версией порогов. Это
    ответ, а не пустота: докупить историю и запустить классификацию."""

    score: float | None = None


class ReasonRow(BaseModel):
    """Одно проверенное условие вердикта — то же, что печатает `explain`."""

    subject: str
    fact: float | None
    threshold: float | None
    passed: bool
    decisive: bool
    note: str = ""
    fact_missing: Literal["not_bought", "no_data"] | None = None
    """Почему факта нет, если его нет.

    Прочерк в карточке означал два разных случая (Z25): историю метрики **не
    покупали** — шаг 2 платится только кандидатам в кейсы, — или купили, а
    Ahrefs ничего не отдал. Заказчик спрашивает «вы не купили или не смогли?»,
    и разница в деньгах: докупить можно только первое.

    Ответ даёт журнал расхода (`collect.purchases.bought_metrics`), а не
    догадка по пустому значению. `None` означает «сказать нечего»: либо факт
    есть, либо условие не про метрику, либо журнал про этот домен молчит —
    тогда экран оставляет прочерк, а не выдумывает причину.
    """


class ComparisonRow(BaseModel):
    """Строка «метрика: было → стало». Та же, что в таблице кейса.

    Подпись и рост считаются **на сервере**: словарь подписей и арифметика
    роста уже существуют для кейса, и вторая копия на фронте разошлась бы с
    первой — экран и PDF начали бы называть метрики по-разному, а рост от
    нулевой базы превратился бы из «не определён» в сто процентов.
    """

    subject: str
    label: str
    before: float
    after: float
    absolute: float
    pct: float | None
    """`None` — рост от нулевой базы: процента у него нет."""


class VerdictView(BaseModel):
    group: str
    score: float
    ruleset_version: str
    decided_at: datetime
    points_note: str = ""
    """Почему «стало» в таблице и конец кривой — разные числа.

    Фраза приходит с сервера, а не пишется на фронте: она же печатается в PDF
    (`export.html_renderer.POINTS_NOTE`), и вторая копия разошлась бы с первой —
    лист и экран начали бы объяснять одно и то же разными словами (Z32)."""

    reasons: list[ReasonRow]
    point_a: dict[str, float]
    point_b: dict[str, float]
    comparison: list[ComparisonRow] = []
    source: str | None = None
    """По каким рядам посчитан вердикт. `null` — вынесен до 14.09.2026, когда
    источник ещё не записывали."""


class SeriesRow(BaseModel):
    """Месячный ряд метрики — под график карточки."""

    metric: str
    points: list[tuple[date, float]]


class ProjectCard(BaseModel):
    project: ProjectRow
    verdict: VerdictView | None
    series: list[SeriesRow]
    series_source: str
    """Откуда прочитаны ряды карточки. Виден на экране рядом с числами
    вердикта: они приходят из разных мест, и человек обязан видеть, из каких."""

    source_mismatch: str | None = None
    """Заполнено, когда числа вердикта посчитаны **не по этим** рядам: таблица
    и кривые на одном экране оказались бы из разных миров (Z10). Решает сервер,
    а не фронт: правило одно на лист PDF и на карточку."""


class CaseRow(BaseModel):
    """Кейс в библиотеке. Имя файла — то самое, что уйдёт клиенту."""

    id: int
    project_id: int
    domain: str
    version: int
    anonymized: bool
    status: str
    created_at: datetime
    filename: str | None = None
    checksum: str | None = None
    case_group: str | None = None
    """Группа, которой кейс собран: файл объясняет ЕЁ, а не сегодняшнюю."""

    current_group: str | None = None
    """Группа проекта по действующему вердикту. `None` — вердикта нет."""

    outdated: Literal["group", "verdict", "numbers", "gone"] | None = None
    """Почему файл больше не объясняет сегодняшнюю группу (Z30).

    Кейс принадлежит вердикту (`Case.verdict_id`), а карточка и библиотека
    показывают действующий. Разойтись им достаточно одного пересчёта: у
    `allthedifferences.com` на экране стояло «плохой, −99,9 %», а файл к нему
    прилагался прежний — «+69 %», собранный по фикстурным рядам. Отдать такой
    клиенту значит отдать чужие числа под именем этого проекта.

    `group` — проекту кейс больше не положен, `verdict` — файл собран другим
    расчётом, `numbers` — расчёт тот же, а числа в нём другие (вердикт
    пересчитан поверх: он пишется upsert'ом и сохраняет прежний `id`),
    `gone` — действующего вердикта у проекта нет. `None` — файл и экран об
    одном.
    """


class PackView(BaseModel):
    """Пачка кейсов на диске: то, что забирают целиком.

    Отсутствие архива — это ответ, а не ошибка: кейсы могли ещё не собираться.
    Поэтому `exists: false` приходит кодом 200 и с пояснением, чем это чинится,
    а `404` остаётся за случаем «просили файл, файла нет» (класс урока L1).
    """

    exists: bool
    filename: str | None = None
    size_bytes: int | None = None
    built_at: datetime | None = None
    note: str
    """Что видит человек: когда собрана пачка, почему её нет или не отдаём."""

    outdated: Literal["project_deleted"] | None = None
    """Почему пачку не отдают: `project_deleted` — в ней кейс удалённого проекта
    (копия PDF в архиве пережила удаление). Лечится пересборкой кейсов."""


class ProjectDeletion(BaseModel):
    """Что удаление проекта уносит и что оставляет. Одна форма на предпросмотр и
    на ответ удаления: экран спрашивает «что уйдёт» и показывает «что ушло»."""

    project_id: int
    domain: str
    metric_points: int
    """Купленные точки рядов — уходят (владелец, 24.09.2026): повторная загрузка
    проекта купит их заново."""

    verdicts: int
    cases: int
    files: int
    """PDF, уходящие с диска: из каталога выгрузки и ничьи больше."""

    run_items: int
    """Строки журнала прогонов. Не уходят: домен, исход и расход остаются."""

    twin_campaigns: int
    """Другие кампании того же сайта: их ряды — свои копии, они остаются."""

    pack_blocked: bool
    """Свежая пачка содержит кейс проекта — после удаления её не отдают до пересборки."""


class UsageView(BaseModel):
    """Расход units: что потрачено, что зарезервировано, что осталось."""

    spent: int
    """Настоящий расход — units живых прогонов по журналу.

    Fixture-прогоны сюда не входят: их units условные, и сложение с настоящими
    делало «потрачено» несравнимым с кабинетом Ahrefs (Z38)."""

    conditional: int = 0
    """Условные units: столько насчитали прогоны без живого ключа по формуле
    живого API. Отдельным числом, а не молчанием: иначе экран говорил бы
    «потрачено 0» рядом с журналом прогонов, где у каждого есть факт."""

    reserved: int
    remaining: int | None = Field(
        default=None,
        description="Остаток по ответу Ahrefs; `null` — остаток не удалось узнать",
    )
    uncounted: int = 0
    """Расход живых прогонов, которого счётчик Ahrefs ещё не увидел.

    Отдельным числом, а не вычетом из `remaining`: остаток обязан оставаться
    сравнимым с тем, что показывает сам Ahrefs, иначе расхождение экрана с
    кабинетом будет выглядеть как ошибка сервиса. Прогон при этом считается по
    разнице — её и показывает экран."""

    live_domains: int = 0
    """Сколько доменов оплачено живьём — различные домены в тех же строках
    журнала, что дают `spent`; знаменатель `per_hundred_domains`. Показывается
    рядом, чтобы метрику можно было пересчитать по экрану, а не принимать на
    веру."""

    per_hundred_domains: int | None = None
    """Метрика успеха из ТЗ: стоимость запуска на 100 URL — `spent` на
    `live_domains`, умноженное на сто. `null` — живого расхода ещё нет."""


class RunAuthor(BaseModel):
    """Кем запускались прогоны — список для отбора в журнале.

    Удалённые учётки остаются: журнал живёт ради вопроса «кто это запускал», и
    отбор, потерявший уволившегося, потерял бы вместе с ним его прогоны.
    """

    id: int
    name: str
    deleted: bool


class RunRow(BaseModel):
    """Прогон в журнале: статус, сколько проектов и сколько units."""

    id: int
    status: str
    started_by: int
    started_by_name: str = ""
    """Кто запустил — именем, а не номером строки.

    Журнал существует ради этого вопроса, и раньше он отвечал на него числом:
    экран показывал прогон без автора вовсе. Имя берётся из учётки, а если её
    удалили — остаётся, потому что строка учётки для того и сохраняется."""

    started_by_deleted: bool = False
    """Учётку автора удалили. В журнале он остаётся с пометкой «(удалён)»:
    ответ «кто запускал» обязан переживать увольнение."""

    stage: str = ""
    """Ступень прогона: `stage1`, `stage2`, `case_data`, `cases`. Пусто — прогон
    старше этого поля, ступень неизвестна (B6: сборка кейсов читалась как сбор)."""

    created_at: datetime
    started_at: datetime | None
    finished_at: datetime | None
    projects_total: int
    projects_ok: int
    projects_failed: int
    projects_skipped: int = 0
    """Проекты, по которым данных не появилось: ни собраны, ни упали.

    Считается вычитанием, а не отдельной колонкой: колонка была бы третьим
    счётчиком рядом с двумя, а источник у всех один — `run_items`. Разошлась бы
    она с записями молча и обнаружилась бы на экране, где объяснять уже поздно
    (тот же довод, что у `run_spend`, считающего расход по журналу)."""

    units_estimated: int
    units_actual: int
    error: str = ""
    live: bool = False
    """Прогон ходил в настоящий Ahrefs — правилом, которым считается «потрачено»
    (`budget._live_run`). `False` — units прогона условные, расходом не считаются."""

    mode: str = ""
    """Режим, записанный при открытии прогона: `live`, `fixture`; пусто — прогон
    старше этого поля. Для слова на экране; живой ли прогон, решает `live`."""


class RunItemView(BaseModel):
    """Судьба одного проекта в прогоне: что с ним стало и почему."""

    domain: str
    outcome: str
    reason: str = ""
    units_actual: int = 0
    project_deleted: bool = False
    """Проект удалён: строка журнала осталась — домен, исход и расход объясняют счёт."""


class RunCard(RunRow):
    """Прогон со списком судеб — то, что открывают, когда «17 из 19» мало.

    Наследник `RunRow`, а не новая модель: экран опрашивает ту же строку, и
    вложенность сломала бы существующего читателя ради поля, которое ему не
    нужно.
    """

    fates: list[RunItemView] = []


class RunStarted(BaseModel):
    """Ответ на запуск: номер прогона и как он поставлен.

    Номер возвращается сразу, потому что строка прогона создаётся обработчиком,
    а не задачей: иначе на вопрос «что я запустил» ответа бы не было до первого
    обращения к Ahrefs.
    """

    run_id: int
    queued_as: str


class RulesetRow(BaseModel):
    """Версия порогов в списке. Содержимое отдаётся целиком: его правят."""

    id: int
    version: str
    is_active: bool
    note: str
    created_at: datetime
    payload: dict[str, object]


class RulesetCreate(BaseModel):
    """Новая версия порогов. Имя версии — ключ, и он неизменяем."""

    version: str = Field(min_length=1, max_length=40)
    note: str = Field(default="", max_length=500)
    payload: dict[str, object]


class PreviewChange(BaseModel):
    domain: str
    was: str | None
    becomes: str


class PreviewView(BaseModel):
    """Что изменится при этой версии порогов — и чего в этом счёте нет.

    Четыре состояния, а не два: сменит группу, получит вердикт впервые, данных
    этой версии не хватает, не изменится (уроки L31 и L32).
    """

    version: str
    total: int
    changes: list[PreviewChange]
    first_time: list[PreviewChange]
    unchanged: int
    missing_data: list[str]


class AlertView(BaseModel):
    """Повод, о котором оператор должен узнать сам."""

    kind: str
    severity: str
    message: str


class RejectionRow(BaseModel):
    """Отклонённая строка источника: где, что и почему.

    `row_no` — номер строки **в файле**, вместе с заголовком: человек пойдёт
    искать её глазами в Excel, и off-by-one стоит ему минуты на каждой строке.
    """

    row_no: int
    field: str
    reason: str
    detail: str = ""


class IntakeReportView(BaseModel):
    """Итог приёма списка.

    Три числа, а не одно: повторная загрузка того же файла законна и обязана
    выглядеть как «обновлено 93», а не как «принято 93» во второй раз.
    """

    origin: str
    accepted: int
    created: int
    updated: int
    rejected_rows: int
    by_reason: dict[str, int]
    rejections: list[RejectionRow]
    notices: list[RejectionRow] = []
    """Непонятые ячейки **принятых** строк. Отдельным полем, потому что
    последствие другое: проект в сервисе есть, а цифру можно уточнить позже.
    Считать их отказами значило бы показать принятые строки потерянными."""


class IntakeLink(BaseModel):
    """Ссылка на опубликованную Google Sheet — второй способ загрузки по ТЗ."""

    url: str = Field(min_length=1, max_length=2000)


class RunEstimate(BaseModel):
    """Во что обойдётся прогон и можно ли его начинать.

    Вердикт тремя состояниями, а не флагом: «не хватает квоты» лечится
    ожиданием или повышением лимита, «остаток неизвестен» — починкой доступа к
    Ahrefs, и показать человеку не ту причину значит отправить его не туда.
    """

    projects: int
    units_estimated: int
    requests_planned: int
    requests_cached: int
    scheme_lines: list[str]
    quota_left: int | None
    quota_reserved: int
    verdict: str
    may_start: bool
    reason: str = ""


class ChartBlock(BaseModel):
    """Готовый график: заголовок и разметка.

    Отдаётся **рисунком**, а не данными для рисования: решение владельца —
    один SVG идёт и в PDF, и в веб-карточку. Отдай мы точки, у фронта
    появилась бы вторая модель графика, и два рисунка разошлись бы на первой
    же правке — клиент и сотрудник увидели бы разные кривые одного проекта.
    """

    title: str
    svg: str
