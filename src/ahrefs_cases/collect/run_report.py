"""Отчёт о прогоне: числа, которые показывают человеку.

Отдельный модуль, а не часть раннера, по той же причине, по которой смета
считается до старта: исполнение и предъявление — разные задачи, и раннер уже
уперся в лимит длины файла. Здесь только форма ответа, ни одного обращения к
базе или провайдеру.

Правило про числа в отчёте одно и оно дорого добыто (урок L13): исход
сворачивается **по проекту**, число задач показывается отдельно. У проекта на
шаге 2 четыре запроса, а в схеме «две точки» — два, и «проектов 3, собрано 12»
человеку показывать нельзя.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class RunReport:
    """Итог прогона в числах, которые показывают человеку."""

    run_id: int
    status: str
    projects_total: int
    projects_ok: int
    projects_skipped: int
    projects_failed: int
    projects_aborted: int
    """Задачи, которых не было: предохранитель остановил прогон. Отдельное
    число, потому что это не «упало», а «не спрашивали» — и повторный прогон
    по ним обязателен."""

    tasks_total: int = 0
    """Задач в прогоне: на шаге 2 их вчетверо больше, чем проектов. Отдельное
    число, потому что «проектов 3, собрано 12» человеку показывать нельзя."""

    points_written: int = 0
    units_spent: int = 0
    units_estimated: int = 0
    """Смета до старта. Хранится рядом с фактом: расхождение между ними —
    единственный способ узнать, что модель стоимости врёт, до Ф7."""

    scheme_lines: tuple[str, ...] = ()
    """Разбивка сметы по способу сбора — требование заказчика к экрану Ф6.

    Строками, а не числами: способов два сегодня и три с ступенью графика в Ф4,
    и отчёт не должен переписываться каждый раз, когда их становится больше."""

    cost_per_100: int = 0
    """«Стоимость запуска на 100 URL» — метрика приёмки, названная заказчиком.

    Отдельным числом в отчёте, а не выводимая из журнала вручную: её обязано
    быть видно сразу после прогона."""

    error: str = ""
    requests_made: int = 0
    requests_saved: int = 0
    """Сколько запросов сделано и сколько не понадобилось. Два числа, а не одно:
    «сделано 0» без «сэкономлено 100» читается как сломанный прогон."""

    def as_lines(self) -> list[str]:
        return [
            f"прогон {self.run_id}: {self.status}",
            f"проектов: {self.projects_total} "
            f"(собрано {self.projects_ok}, пропущено {self.projects_skipped}, "
            f"упало {self.projects_failed}, не выполнено {self.projects_aborted})",
            f"задач: {self.tasks_total}",
            f"точек записано: {self.points_written}",
            f"запросов: сделано {self.requests_made}, сэкономлено кэшем {self.requests_saved}",
            f"units: смета {self.units_estimated}, потрачено {self.units_spent}",
            *self.scheme_lines,
            f"стоимость запуска на 100 URL: {self.cost_per_100} units",
            *([f"причина: {self.error}"] if self.error else []),
        ]
