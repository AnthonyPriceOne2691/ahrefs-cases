"""Откуда читать ряды: один ответ на всю командную строку.

Вопросов два, и они разные. **«Откуда покупать»** — режим провайдера: за него
платит заказчик, и переключает его человек. **«Что читать»** — источник уже
купленных точек в базе: чтение не делает ни одного запроса к Ahrefs и ключом не
пользуется.

Пока ответ был один на оба вопроса, собрать кейс по купленным живым рядам можно
было, только подняв живой режим, — то есть сняв предохранитель ради безопасной
операции (урок L138). Флаг `--source` это развёл, но получили его лишь три
команды, оказавшиеся тогда под рукой: считающие остались на режиме провайдера, и
пересчёт вердиктов по живым рядам снова требовал живого режима (Z11, урок L142).

Поэтому правило живёт здесь, а не по экземпляру в каждом модуле команд: два
экземпляра расходятся не в тот день, когда их пишут, а в тот, когда добавляют
третью команду.
"""

from __future__ import annotations

import argparse

from ahrefs_cases import config
from ahrefs_cases.storage._enums import MetricSource


def provider_source() -> MetricSource:
    """Каким источником помечаются точки текущего режима.

    Ответ на «откуда покупать». Им же помечается купленное, поэтому платящая
    команда читает и пишет **в одном** режиме: выбрать фикстурные ряды и купить
    по ним живые данные значило бы записать в базу точки под чужим именем.
    """
    return MetricSource.LIVE if config.ahrefs.provider == "live" else MetricSource.FIXTURE


def reading_source(chosen: MetricSource | None) -> MetricSource:
    """Ответ на «что читать»: названное вызывающим или, если не назвал, режим.

    Умолчание осталось только у режима: кто назвал источник, тот его и выбрал.
    Собственного умолчания у чтения нет — трижды подряд `source=FIXTURE` в
    сигнатуре приводил к одному и тому же: в живом режиме сервис читал пустоту
    и отвечал «данных нет» при целой базе (урок L107).
    """
    return chosen if chosen is not None else provider_source()


def named(args: argparse.Namespace) -> MetricSource | None:
    """Источник, названный флагом `--source`. `None` — не назван.

    Разбор здесь, а не в скрипте, потому что флаг у команд общий: строка
    `args.source` в каждой из десяти команд — десять мест, где опечатка тихо
    вернёт режим провайдера вместо названного.
    """
    chosen = getattr(args, "source", None)
    if not chosen:
        return None
    return MetricSource.LIVE if chosen == "live" else MetricSource.FIXTURE
